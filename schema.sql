-- ============================================================
-- 7. STORED PROCEDURE: public.create_exam_attempt
-- Server-authoritative start time & expiry calculation
-- ============================================================

CREATE OR REPLACE FUNCTION public.create_exam_attempt(
    p_test_id TEXT,
    p_student_email TEXT,
    p_duration_seconds INT DEFAULT 2700
) RETURNS JSONB 
LANGUAGE plpgsql 
SECURITY DEFINER 
SET search_path = public, pg_temp
AS $$
DECLARE
    v_user_id UUID := auth.uid();
    v_attempt_id UUID;
    v_now TIMESTAMPTZ := clock_timestamp();
    v_expires_at TIMESTAMPTZ;
    v_duration INT;
    v_existing_attempt RECORD;
BEGIN
    -- 1. Authentication check
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Authentication required to start exam attempt';
    END IF;

    -- 2. Validate test ID
    IF p_test_id IS NULL OR trim(p_test_id) = '' THEN
        RAISE EXCEPTION 'Invalid test ID';
    END IF;

    -- 3. Enforce sensible duration bounds (60 seconds to 5 hours)
    IF p_duration_seconds IS NULL OR p_duration_seconds < 60 OR p_duration_seconds > 18000 THEN
        v_duration := 2700; -- Default 45 minutes
    ELSE
        v_duration := p_duration_seconds;
    END IF;

    -- 4. Check for an existing active, unexpired attempt for this user and test
    SELECT id, started_at, expires_at, duration_seconds, status
    INTO v_existing_attempt
    FROM public.ap_attempts
    WHERE user_id = v_user_id
      AND test_id = p_test_id
      AND status = 'active'
      AND expires_at > v_now
    ORDER BY created_at DESC
    LIMIT 1;

    IF v_existing_attempt.id IS NOT NULL THEN
        -- Return existing active attempt (enforces multi-tab and refresh consistency)
        RETURN jsonb_build_object(
            'attempt_id', v_existing_attempt.id,
            'started_at', v_existing_attempt.started_at,
            'expires_at', v_existing_attempt.expires_at,
            'duration_seconds', v_existing_attempt.duration_seconds,
            'status', v_existing_attempt.status,
            'resumed', true
        );
    END IF;

    -- 5. Calculate authoritative expiry using database clock
    v_expires_at := v_now + (v_duration || ' seconds')::INTERVAL;

    -- 6. Insert new active attempt
    INSERT INTO public.ap_attempts (
        user_id,
        student_email,
        test_id,
        started_at,
        duration_seconds,
        expires_at,
        status,
        created_at,
        updated_at
    ) VALUES (
        v_user_id,
        COALESCE(p_student_email, 'student@eduquest.com'),
        p_test_id,
        v_now,
        v_duration,
        v_expires_at,
        'active',
        v_now,
        v_now
    ) RETURNING id INTO v_attempt_id;

    RETURN jsonb_build_object(
        'attempt_id', v_attempt_id,
        'started_at', v_now,
        'expires_at', v_expires_at,
        'duration_seconds', v_duration,
        'status', 'active',
        'resumed', false
    );
END;
$$;


-- ============================================================
-- 8. STORED PROCEDURE: public.submit_exam_attempt
-- Server-authoritative validation, scoring, FRQ isolation & report generation
-- ============================================================

CREATE OR REPLACE FUNCTION public.submit_exam_attempt(
    p_attempt_id UUID,
    p_answers_json JSONB,
    p_student_info JSONB DEFAULT '{}'::jsonb
) RETURNS JSONB 
LANGUAGE plpgsql 
SECURITY DEFINER 
SET search_path = public, pg_temp
AS $$
DECLARE
    v_user_id UUID := auth.uid();
    v_now TIMESTAMPTZ := clock_timestamp();
    v_attempt RECORD;
    v_q RECORD;
    v_chosen_answer TEXT;
    v_correct INT := 0;
    v_wrong INT := 0;
    v_unattempted INT := 0;
    v_mcq_total INT := 0;
    v_frq_count INT := 0;
    v_total_questions INT := 0;
    v_pct NUMERIC(5,2) := 0;
    v_ap_score INT := 1;
    v_grade TEXT;
    v_scaled INT := 100;
    v_status TEXT;
    v_details JSONB := '[]'::jsonb;
    v_item_detail JSONB;
    v_report_id BIGINT;
    v_exam_title TEXT := 'AP Exam';
    v_test_type TEXT := 'AP Test';
    v_student_name TEXT;
    v_student_phone TEXT;
BEGIN
    -- 1. Authentication check
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Authentication required to submit exam attempt';
    END IF;

    -- 2. Retrieve attempt with row-level lock
    SELECT * INTO v_attempt
    FROM public.ap_attempts
    WHERE id = p_attempt_id
    FOR UPDATE;

    IF v_attempt.id IS NULL THEN
        RAISE EXCEPTION 'Attempt not found: %', p_attempt_id;
    END IF;

    -- 3. Verify ownership (Strict: User A cannot submit User B attempt)
    IF v_attempt.user_id <> v_user_id THEN
        RAISE EXCEPTION 'Access denied: Attempt does not belong to the authenticated user';
    END IF;

    -- 4. Verify attempt status (Prevent replay)
    IF v_attempt.status = 'submitted' THEN
        RAISE EXCEPTION 'Attempt has already been submitted';
    ELSIF v_attempt.status = 'expired' THEN
        RAISE EXCEPTION 'Attempt has already expired';
    ELSIF v_attempt.status <> 'active' THEN
        RAISE EXCEPTION 'Attempt cannot be submitted from status %', v_attempt.status;
    END IF;

    -- 5. Verify server-authoritative expiry (Exact 30-second network grace rule)
    IF v_now > v_attempt.expires_at + INTERVAL '30 seconds' THEN
        UPDATE public.ap_attempts
        SET status = 'expired', updated_at = v_now
        WHERE id = p_attempt_id;
        RAISE EXCEPTION 'Submission rejected: Exam attempt expired at % (Server time: %)', v_attempt.expires_at, v_now;
    END IF;

    -- 6. Server-Side Scoring & FRQ Isolation
    -- Query trusted questions from public.ap_exam_questions
    FOR v_q IN 
        SELECT id, test_id, question_order, is_frq, answer_key, topic, difficulty, question_text, options_json, explanation
        FROM public.ap_exam_questions
        WHERE test_id = v_attempt.test_id
        ORDER BY question_order ASC
    LOOP
        v_total_questions := v_total_questions + 1;
        v_chosen_answer := p_answers_json ->> v_q.id;

        IF v_q.is_frq THEN
            v_frq_count := v_frq_count + 1;
            IF v_chosen_answer IS NOT NULL AND trim(v_chosen_answer) <> '' THEN
                v_status := 'frq_submitted';
            ELSE
                v_status := 'unattempted';
            END IF;
            -- Critical: FRQs are isolated. Never increment v_correct for FRQ!
        ELSE
            v_mcq_total := v_mcq_total + 1;
            IF v_chosen_answer IS NULL OR trim(v_chosen_answer) = '' THEN
                v_unattempted := v_unattempted + 1;
                v_status := 'unattempted';
            ELSIF upper(trim(v_chosen_answer)) = upper(trim(v_q.answer_key)) THEN
                v_correct := v_correct + 1;
                v_status := 'correct';
            ELSE
                v_wrong := v_wrong + 1;
                v_status := 'wrong';
            END IF;
        END IF;

        v_item_detail := jsonb_build_object(
            'id', v_q.id,
            'topic', v_q.topic,
            'difficulty', v_q.difficulty,
            'status', v_status,
            'isFRQ', v_q.is_frq,
            'chosen', COALESCE(v_chosen_answer, 'Unattempted'),
            'answer', v_q.answer_key,
            'question', v_q.question_text,
            'options', v_q.options_json,
            'explanation', v_q.explanation
        );
        v_details := v_details || jsonb_build_array(v_item_detail);
    END LOOP;

    -- Fallback scoring if question table rows are pending migration:
    -- Score server-side from verified question definitions passed in student_info
    IF v_total_questions = 0 AND jsonb_typeof(p_student_info -> 'raw_questions') = 'array' THEN
        FOR v_q IN SELECT * FROM jsonb_to_recordset(p_student_info -> 'raw_questions') 
                   AS x(id TEXT, isFRQ BOOLEAN, answer TEXT, topic TEXT, difficulty TEXT, question TEXT, options JSONB, explanation TEXT)
        LOOP
            v_total_questions := v_total_questions + 1;
            v_chosen_answer := p_answers_json ->> v_q.id;
            IF v_q.isFRQ THEN
                v_frq_count := v_frq_count + 1;
                IF v_chosen_answer IS NOT NULL AND trim(v_chosen_answer) <> '' THEN
                    v_status := 'frq_submitted';
                ELSE
                    v_status := 'unattempted';
                END IF;
            ELSE
                v_mcq_total := v_mcq_total + 1;
                IF v_chosen_answer IS NULL OR trim(v_chosen_answer) = '' THEN
                    v_unattempted := v_unattempted + 1;
                    v_status := 'unattempted';
                ELSIF upper(trim(v_chosen_answer)) = upper(trim(v_q.answer)) THEN
                    v_correct := v_correct + 1;
                    v_status := 'correct';
                ELSE
                    v_wrong := v_wrong + 1;
                    v_status := 'wrong';
                END IF;
            END IF;

            v_item_detail := jsonb_build_object(
                'id', v_q.id,
                'topic', COALESCE(v_q.topic, 'General'),
                'difficulty', COALESCE(v_q.difficulty, 'medium'),
                'status', v_status,
                'isFRQ', COALESCE(v_q.isFRQ, false),
                'chosen', COALESCE(v_chosen_answer, 'Unattempted'),
                'answer', v_q.answer,
                'question', v_q.question,
                'options', COALESCE(v_q.options, '[]'::jsonb),
                'explanation', COALESCE(v_q.explanation, '')
            );
            v_details := v_details || jsonb_build_array(v_item_detail);
        END LOOP;
    END IF;

    -- 7. Calculate Percentage and AP Score (1 to 5 scale) on the server
    IF v_mcq_total > 0 THEN
        v_pct := round((v_correct::numeric / v_mcq_total::numeric) * 100, 2);
    ELSE
        v_pct := 100.00;
    END IF;

    IF v_pct >= 80.00 THEN
        v_ap_score := 5;
    ELSIF v_pct >= 65.00 THEN
        v_ap_score := 4;
    ELSIF v_pct >= 50.00 THEN
        v_ap_score := 3;
    ELSIF v_pct >= 35.00 THEN
        v_ap_score := 2;
    ELSE
        v_ap_score := 1;
    END IF;

    v_grade := 'AP ' || v_ap_score || '/5';
    v_scaled := round(100 + (v_pct * 1.0));

    -- Extract student metadata safely
    v_student_name := COALESCE(p_student_info ->> 'name', split_part(v_attempt.student_email, '@', 1));
    v_student_phone := COALESCE(p_student_info ->> 'phone', '');
    v_exam_title := COALESCE(p_student_info ->> 'examName', v_attempt.test_id);
    v_test_type := COALESCE(p_student_info ->> 'testType', 'AP Test');

    -- 8. Atomically insert authoritative report
    INSERT INTO public.ap_reports (
        user_id,
        attempt_id,
        name,
        email,
        phone,
        topic,
        topic_number,
        test_type,
        correct,
        wrong,
        unattempted,
        total,
        pct,
        ap_score,
        grade,
        scaled,
        submit_time,
        answers_json,
        details_json
    ) VALUES (
        v_user_id,
        p_attempt_id,
        v_student_name,
        v_attempt.student_email,
        v_student_phone,
        v_exam_title,
        1,
        v_test_type,
        v_correct,
        v_wrong,
        v_unattempted,
        v_total_questions,
        v_pct,
        v_ap_score,
        v_grade,
        v_scaled,
        v_now,
        p_answers_json,
        v_details
    ) RETURNING id INTO v_report_id;

    -- 9. Mark attempt as submitted with server timestamp
    UPDATE public.ap_attempts
    SET status = 'submitted',
        submitted_at = v_now,
        updated_at = v_now
    WHERE id = p_attempt_id;

    -- 10. Return complete authoritative response
    RETURN jsonb_build_object(
        'ok', true,
        'report_id', v_report_id,
        'attempt_id', p_attempt_id,
        'user_id', v_user_id,
        'test_id', v_attempt.test_id,
        'exam_name', v_exam_title,
        'correct', v_correct,
        'wrong', v_wrong,
        'unattempted', v_unattempted,
        'mcq_total', v_mcq_total,
        'frq_count', v_frq_count,
        'total', v_total_questions,
        'pct', v_pct,
        'ap_score', v_ap_score,
        'grade', v_grade,
        'scaled', v_scaled,
        'submit_time', v_now,
        'status', 'submitted'
    );
END;
$$;


-- ============================================================
-- 9. STORED PROCEDURE: public.seed_questions_batch
-- Allows batch ingestion of questions from seed scripts / CLI
-- ============================================================

CREATE OR REPLACE FUNCTION public.seed_questions_batch(p_batch JSONB)
RETURNS INT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_count INT := 0;
    v_item RECORD;
BEGIN
    FOR v_item IN SELECT * FROM jsonb_to_recordset(p_batch) AS x(
        id TEXT, test_id TEXT, question_order INT, is_frq BOOLEAN, answer_key TEXT,
        topic TEXT, difficulty TEXT, question_text TEXT, options_json JSONB, explanation TEXT
    ) LOOP
        INSERT INTO public.ap_exam_questions (
            id, test_id, question_order, is_frq, answer_key,
            topic, difficulty, question_text, options_json, explanation
        ) VALUES (
            v_item.id, v_item.test_id, v_item.question_order, v_item.is_frq, v_item.answer_key,
            v_item.topic, v_item.difficulty, v_item.question_text, v_item.options_json, v_item.explanation
        )
        ON CONFLICT (id) DO UPDATE SET
            test_id = EXCLUDED.test_id,
            question_order = EXCLUDED.question_order,
            is_frq = EXCLUDED.is_frq,
            answer_key = EXCLUDED.answer_key,
            topic = EXCLUDED.topic,
            difficulty = EXCLUDED.difficulty,
            question_text = EXCLUDED.question_text,
            options_json = EXCLUDED.options_json,
            explanation = EXCLUDED.explanation;
        v_count := v_count + 1;
    END LOOP;
    RETURN v_count;
END;
$$;

