-- ============================================================
-- EDUQUEST AP MOCK TEST PLATFORM - SUPABASE DATABASE SCHEMA
-- ============================================================

-- 1. Main Profiles Table (public.profiles) - synced with auth.users and shared across EduQuest platforms
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY,
    email TEXT UNIQUE NOT NULL,
    full_name TEXT,
    phone TEXT,
    has_ap_diag_access BOOLEAN DEFAULT FALSE,
    has_ap_topic_access BOOLEAN DEFAULT FALSE,
    has_ap_mock_access BOOLEAN DEFAULT FALSE,
    has_ap_access BOOLEAN DEFAULT FALSE,
    unlocked_tests JSONB DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Add AP access columns if public.profiles table already exists (e.g. from SAT platform)
ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS has_ap_diag_access BOOLEAN DEFAULT FALSE;
ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS has_ap_topic_access BOOLEAN DEFAULT FALSE;
ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS has_ap_mock_access BOOLEAN DEFAULT FALSE;
ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS has_ap_access BOOLEAN DEFAULT FALSE;
ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS unlocked_tests JSONB DEFAULT '[]'::jsonb;

-- Enable RLS on profiles
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Public read profiles" ON public.profiles
    FOR SELECT USING (true);

CREATE POLICY "Users can update own profiles" ON public.profiles
    FOR UPDATE USING (auth.uid() = id);

CREATE POLICY "Service role full access profiles" ON public.profiles
    FOR ALL USING (true);


-- 1b. AP Profiles Table (Standalone / Fallback)
CREATE TABLE IF NOT EXISTS public.ap_profiles (
    id UUID PRIMARY KEY,
    email TEXT UNIQUE NOT NULL,
    full_name TEXT,
    phone TEXT,
    has_ap_diag_access BOOLEAN DEFAULT FALSE,
    has_ap_topic_access BOOLEAN DEFAULT FALSE,
    has_ap_mock_access BOOLEAN DEFAULT FALSE,
    has_ap_access BOOLEAN DEFAULT FALSE,
    unlocked_tests JSONB DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.ap_profiles ADD COLUMN IF NOT EXISTS has_ap_access BOOLEAN DEFAULT FALSE;

-- Enable RLS on ap_profiles
ALTER TABLE public.ap_profiles ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Public read ap_profiles" ON public.ap_profiles
    FOR SELECT USING (true);

CREATE POLICY "Users can update own ap_profiles" ON public.ap_profiles
    FOR UPDATE USING (auth.uid() = id);

CREATE POLICY "Service role full access ap_profiles" ON public.ap_profiles
    FOR ALL USING (true);


-- 2. AP Registration / User Logins Table (ap_user)
CREATE TABLE IF NOT EXISTS public.ap_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL,
    phone TEXT,
    topic TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Enable RLS on ap_user
ALTER TABLE public.ap_user ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public insert to ap_user" ON public.ap_user
    FOR INSERT WITH CHECK (true);

CREATE POLICY "Allow public read from ap_user" ON public.ap_user
    FOR SELECT USING (true);


-- 3. AP Test Reports Table (ap_reports)
CREATE TABLE IF NOT EXISTS public.ap_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL,
    phone TEXT,
    topic TEXT NOT NULL,
    topic_number INT DEFAULT 1,
    test_type TEXT DEFAULT 'AP Test', -- Diagnostic, Topic, Full Mock
    correct INT DEFAULT 0,
    wrong INT DEFAULT 0,
    unattempted INT DEFAULT 0,
    total INT DEFAULT 0,
    pct NUMERIC(5,2) DEFAULT 0,
    ap_score INT DEFAULT 1, -- AP Score 1 to 5 scale
    grade TEXT DEFAULT 'N/A',
    scaled INT DEFAULT 0,
    submit_time TIMESTAMPTZ DEFAULT NOW(),
    answers_json JSONB,
    details_json JSONB
);

-- Enable RLS on ap_reports
ALTER TABLE public.ap_reports ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public insert to ap_reports" ON public.ap_reports
    FOR INSERT WITH CHECK (true);

CREATE POLICY "Allow public read from ap_reports" ON public.ap_reports
    FOR SELECT USING (true);


-- 4. AP Test Access Codes / Unlocks Table (ap_test_access)
CREATE TABLE IF NOT EXISTS public.ap_test_access (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL,
    test_id TEXT NOT NULL,
    access_code TEXT UNIQUE NOT NULL,
    is_used BOOLEAN DEFAULT FALSE,
    granted_by TEXT DEFAULT 'admin',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Enable RLS on ap_test_access
ALTER TABLE public.ap_test_access ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public read ap_test_access" ON public.ap_test_access
    FOR SELECT USING (true);

CREATE POLICY "Allow public insert/update ap_test_access" ON public.ap_test_access
    FOR ALL USING (true);
